"""Regenerate docs/CODEMAP.md — where every route, function and page script lives (file:line).

Run after moving / adding code:   python tools/codemap.py
Claude reads ONE grep of this file instead of searching 19,000 lines of Python and 40,000 lines of templates.
"""
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'docs' / 'CODEMAP.md'
PY = [ROOT / 'app.py'] + sorted((ROOT / 'app_parts').glob('p*.py')) + sorted((ROOT / 'core').glob('*.py'))
JS = sorted((ROOT / 'static' / 'js').glob('*.js')) + [ROOT / 'chrome_extension' / 'content.js',
                                                      ROOT / 'chrome_extension' / 'background.js']
TEMPLATES = sorted((ROOT / 'templates').glob('*.html'))

# window.X = function / X.y = (...) => / function name( / const name = (...) =>
JS_DEF = re.compile(r'^\s*(?:window\.([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?(?:function|\()|'
                    r'([A-Z][\w$]*\.[A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?(?:\(|function|[a-z_$][\w$]*\s*=>)|'
                    r'(?:async\s+)?function\s+([A-Za-z_$][\w$]*)\s*\()')


def rel(p):
    return p.relative_to(ROOT).as_posix()


def first_doc_line(node):
    doc = ast.get_docstring(node) or ''
    line = doc.strip().splitlines()[0] if doc.strip() else ''
    return (' — ' + line[:110]) if line else ''


def py_section(path):
    src = path.read_text(encoding='utf-8')
    try:
        tree = ast.parse(src)
    except SyntaxError as e:
        return [f'- ⚠️ cannot parse: {e}']
    head = src.splitlines()[0] if path.parent.name == 'app_parts' else ''
    rows = [f'_{head.lstrip("# ").strip()}_'] if head else []
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        routes = []
        for d in getattr(node, 'decorator_list', []):
            if isinstance(d, ast.Call) and getattr(d.func, 'attr', '') == 'route' and d.args \
                    and isinstance(d.args[0], ast.Constant):
                meth = next((kw.value for kw in d.keywords if kw.arg == 'methods'), None)
                m = ''
                if isinstance(meth, (ast.List, ast.Tuple)):
                    m = ' ' + ','.join(e.value for e in meth.elts if isinstance(e, ast.Constant))
                routes.append(f'`{d.args[0].value}`{m}')
        kind = 'class ' if isinstance(node, ast.ClassDef) else ''
        r = (' ← ' + ' · '.join(routes)) if routes else ''
        rows.append(f'- {rel(path)}:{node.lineno} {kind}`{node.name}`{r}{first_doc_line(node)}')
    return rows


def js_section(path, html=False):
    rows = []
    for i, line in enumerate(path.read_text(encoding='utf-8', errors='replace').splitlines(), 1):
        m = JS_DEF.match(line)
        if m:
            name = next(g for g in m.groups() if g)
            rows.append(f'{i} `{name}`')
    if not rows:
        return []
    # one compact line per ~8 names keeps the map short
    return [f'- {rel(path)}: ' + ' · '.join(rows[i:i + 8]) for i in range(0, len(rows), 8)]


def main():
    out = ['# CODEMAP — where things live (generated by `python tools/codemap.py`, do not edit by hand)', '',
           'Python: `app.py` (setup, config, helpers) then `app_parts/pNN_*.py`, executed in order inside app.py\'s',
           'namespace (one shared global namespace — a helper defined in any part is visible to later ones).',
           'Routes are listed as `← /path METHODS`. Line numbers are 1-based. Templates list their JS functions.', '']
    for p in PY:
        lines = len(p.read_text(encoding='utf-8').splitlines())
        out += [f'## {rel(p)} ({lines} lines)'] + py_section(p) + ['']
    out += ['# JavaScript', '']
    for p in JS:
        if p.exists():
            sec = js_section(p)
            if sec:
                out += [f'## {rel(p)}'] + sec + ['']
    out += ['# Templates (inline JS functions)', '']
    for p in TEMPLATES:
        sec = js_section(p, html=True)
        n = len(p.read_text(encoding='utf-8', errors='replace').splitlines())
        out += [f'## {rel(p)} ({n} lines)'] + (sec or ['- (no named functions)']) + ['']
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'wrote {rel(OUT)}: {len(out)} lines')


if __name__ == '__main__':
    main()
